class I18nManager {
  constructor() {
    this.currentLang = 'en';
    this.init();
  }

  init() {
    try {
      const stored = localStorage.getItem('aitmad_lang');
      if (stored === 'ur' || stored === 'en') {
        this.currentLang = stored;
      }
    } catch (e) {
      this.currentLang = 'en';
    }
    this.applyLanguage(this.currentLang);
  }

  applyLanguage(lang) {
    this.currentLang = lang;
    try {
      localStorage.setItem('aitmad_lang', lang);
    } catch (e) {}

    const html = document.documentElement;
    if (lang === 'ur') {
      html.setAttribute('dir', 'rtl');
      html.setAttribute('lang', 'ur');
    } else {
      html.setAttribute('dir', 'ltr');
      html.setAttribute('lang', 'en');
    }

    // Update all elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.setAttribute('placeholder', translations[lang][key]);
        } else {
          el.innerHTML = translations[lang][key];
        }
      }
    });

    // Update Language Toggle button texts
    const toggleBtns = document.querySelectorAll('.lang-toggle-btn');
    toggleBtns.forEach(btn => {
      btn.innerHTML = lang === 'en' 
        ? `<svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><path d="M2 12h20M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/></svg> <span>اردو</span>`
        : `<svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><path d="M2 12h20M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/></svg> <span>English</span>`;
    });

    // Dispatch event for other modules
    window.dispatchEvent(new CustomEvent('aitmad:langchange', { detail: { lang } }));
  }

  toggleLanguage() {
    const newLang = this.currentLang === 'en' ? 'ur' : 'en';
    this.applyLanguage(newLang);
  }
}

export const i18n = new I18nManager();
